// Reference adapter: plain `docker compose` + Caddy (REDTEAM M2, C300 P10). It is the EXIT PATH and a CONFORMANCE FIXTURE, not a product:
// it exists so the engine contract is tested against a second, tiny engine on every host-agent release, and so a swap away from
// Openship (tripwires in SPRINT-S1-OWN-VPS.md) starts from something that already passes the suite.
//
// Shape: one compose project per workspace (`tbws-<ws>`, its own network and named volumes) plus ONE Caddy on the box (host network)
// that terminates TLS for the public hosts and proxies to 127.0.0.1:<hostPort> of the bridge. Nothing else is published. The
// adapter GENERATES the compose file from the closed HostServiceSpec; it never accepts compose from outside (B3) and the generated
// file has no network_mode, pid, ipc, privileged, cap_add, devices, bind mounts or docker.sock.
//
// render() is pure and runs in CI. apply/stop/status run docker through the injected Runner (same Runner as box.ts), so they are unit
// tested with a fake and exercised for real by the live conformance rows (TB_FIXTURE_LIVE=1) on a box with Docker.
import { createHash, randomBytes } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { type Runner, run } from "../box.ts";
import type { EngineAdapter, Rendered, ServiceName, ServiceStatus, StackSpec } from "./contract.ts";
import { validateStack } from "./schema.ts";

export interface ComposeCaddyConfig {
  r: Runner;
  /** state dir of the fixture: compose files, env files (0600), caddy snippets, stopped.json */
  stateDir: string;
  /** ACME contact for Caddy's certificates (Let's Encrypt HTTP-01). */
  acmeEmail: string;
  /** Caddy image, pinned by digest by the caller (no default on purpose: a default would be a floating pin). */
  caddyImage: string;
  /** Secret generator; tests inject a fixed one. */
  randomSecret?: () => string;
}

const project = (ws: string) => `tbws-${ws}`;
const volumeName = (ws: string, service: string, vol: string) => `${project(ws)}_${service}_${vol}`;

/** Deterministic default loopback port (20000-29999) for a public service; the agent overrides it from its own registry on a clash. */
export function defaultHostPort(ws: string, service: string): number {
  const h = createHash("sha256").update(`${ws}/${service}`).digest();
  return 20000 + (h.readUInt16BE(0) % 10000);
}

const q = (s: string) => JSON.stringify(s); // YAML double-quoted scalars are JSON strings

export class ComposeCaddyAdapter implements EngineAdapter {
  readonly name = "compose-caddy";
  private readonly c: ComposeCaddyConfig;
  constructor(config: ComposeCaddyConfig) {
    this.c = config;
  }

  private paths(ws: string) {
    const dir = join(this.c.stateDir, "stacks", ws);
    return {
      dir,
      compose: join(dir, "compose.yaml"),
      envDir: join(dir, "env"),
      caddy: join(this.c.stateDir, "caddy", `${ws}.caddy`),
      stopped: join(dir, "stopped.json"),
    };
  }

  render(stackIn: StackSpec): Rendered {
    const stack = validateStack(stackIn);
    const ws = stack.workspace;
    const p = this.paths(ws);
    const lines: string[] = [
      "# GENERATED by ComposeCaddyAdapter from the closed service schema. Do not edit; nothing here is read back as input.",
      `name: ${project(ws)}`,
      "networks:",
      "  stack:",
      `    name: ${project(ws)}`,
      "    driver: bridge",
      "volumes:",
    ];
    const vols = stack.services.flatMap((s) => s.volumes.map((v) => ({ s, v })));
    if (!vols.length) lines[lines.length - 1] = "volumes: {}";
    for (const { s, v } of vols) lines.push(`  ${s.serviceName}_${v.name}:`, `    name: ${volumeName(ws, s.serviceName, v.name)}`);
    lines.push("services:");
    for (const s of stack.services) {
      lines.push(
        `  ${s.serviceName}:`,
        `    image: ${s.release.image}`,
        "    restart: unless-stopped",
        "    init: true",
        '    security_opt: ["no-new-privileges:true"]',
        "    networks: [stack]",
      );
      lines.push(`    env_file: [${q(join(p.envDir, `${s.serviceName}.env`))}]`);
      if (s.volumes.length) lines.push("    volumes:", ...s.volumes.map((v) => `      - ${q(`${s.serviceName}_${v.name}:${v.mountPath}`)}`));
      if (s.publicDomain && s.port !== null) {
        const hostPort = stack.hostPorts?.[s.serviceName] ?? defaultHostPort(ws, s.serviceName);
        lines.push("    ports:", `      - ${q(`127.0.0.1:${hostPort}:${s.port}`)}`);
      }
      if (s.resources?.cpu !== undefined) lines.push(`    cpus: ${s.resources.cpu}`);
      if (s.resources?.memoryMb !== undefined) lines.push(`    mem_limit: ${q(`${s.resources.memoryMb}m`)}`);
      lines.push("    pids_limit: 512");
    }
    const documents: Rendered["documents"] = [{ name: "compose.yaml", text: `${lines.join("\n")}\n` }];

    const pub = stack.services.find((s) => s.publicDomain);
    if (pub?.publicHosts && pub.port !== null) {
      const hostPort = stack.hostPorts?.[pub.serviceName] ?? defaultHostPort(ws, pub.serviceName);
      const block = (host: string) => `${host} {\n  reverse_proxy 127.0.0.1:${hostPort}\n}\n`;
      documents.push({ name: `${ws}.caddy`, text: `# GENERATED for workspace ${ws}\n${block(pub.publicHosts.main)}\n${block(pub.publicHosts.keys)}` });
    }
    // the env files: names only here. Values (public env, resolved refs, generated secrets) exist only on the box, mode 0600.
    for (const s of stack.services) {
      const names = [...Object.keys(s.env), ...Object.keys(s.serviceRefs ?? {}), ...s.generatedSecrets].sort();
      documents.push({ name: `env/${s.serviceName}.names`, text: `${names.join("\n")}\n` });
    }
    return { engine: this.name, documents };
  }

  scopeOf(stackIn: StackSpec): { networks: string[]; volumes: string[] } {
    const stack = validateStack(stackIn);
    return {
      networks: [project(stack.workspace)],
      volumes: stack.services.flatMap((s) => s.volumes.map((v) => volumeName(stack.workspace, s.serviceName, v.name))).sort(),
    };
  }

  originsFor(stackIn: StackSpec): string[] {
    const stack = validateStack(stackIn);
    return stack.services
      .filter((s) => !s.publicDomain && s.port !== null)
      .map((s) => `http://${s.serviceName}:${s.port}`)
      .sort();
  }

  private secretStore(ws: string): { get(name: string): string } {
    const dir = join(this.c.stateDir, "secrets");
    mkdirSync(dir, { recursive: true, mode: 0o700 });
    const file = join(dir, `${ws}.json`);
    const all: Record<string, string> = existsSync(file) ? JSON.parse(readFileSync(file, "utf8")) : {};
    return {
      get: (name: string) => {
        if (!all[name]) {
          all[name] = (this.c.randomSecret ?? (() => randomBytes(32).toString("hex")))();
          writeFileSync(file, JSON.stringify(all), { mode: 0o600 });
        }
        return all[name] as string;
      },
    };
  }

  private stoppedSet(ws: string): Set<string> {
    const f = this.paths(ws).stopped;
    return new Set(existsSync(f) ? (JSON.parse(readFileSync(f, "utf8")) as string[]) : []);
  }

  async apply(stackIn: StackSpec): Promise<void> {
    const stack = validateStack(stackIn);
    const ws = stack.workspace;
    const p = this.paths(ws);
    const rendered = this.render(stack);
    mkdirSync(p.envDir, { recursive: true, mode: 0o700 });
    mkdirSync(join(this.c.stateDir, "caddy"), { recursive: true, mode: 0o700 });
    const secrets = this.secretStore(ws);
    for (const s of stack.services) {
      const kv: string[] = Object.entries(s.env).map(([k, v]) => `${k}=${v}`);
      // refs: the value of the referenced service's env entry or generated secret (rendered here, on the box, never sent by Core)
      for (const [k, ref] of Object.entries(s.serviceRefs ?? {})) {
        const t = stack.services.find((x) => x.serviceName === ref.serviceName);
        kv.push(`${k}=${t && ref.env in t.env ? t.env[ref.env] : secrets.get(`${ref.serviceName}.${ref.env}`)}`);
      }
      for (const name of s.generatedSecrets) kv.push(`${name}=${secrets.get(`${s.serviceName}.${name}`)}`);
      writeFileSync(join(p.envDir, `${s.serviceName}.env`), `${kv.join("\n")}\n`, { mode: 0o600 });
    }
    writeFileSync(p.compose, (rendered.documents.find((d) => d.name === "compose.yaml") as { text: string }).text, { mode: 0o600 });
    const caddy = rendered.documents.find((d) => d.name === `${ws}.caddy`);
    if (caddy) writeFileSync(p.caddy, caddy.text, { mode: 0o644 });
    const stopped = this.stoppedSet(ws);
    const up = stack.services.map((s) => s.serviceName).filter((n) => !stopped.has(n));
    await run(this.c.r, "docker", ["compose", "-f", p.compose, "up", "-d", ...up]);
    await this.ensureCaddy();
    if (caddy) await run(this.c.r, "docker", ["exec", "tb-caddy", "caddy", "reload", "--config", "/etc/caddy/Caddyfile"]);
  }

  /** One Caddy per box on the host network; imports every workspace snippet. */
  private async ensureCaddy(): Promise<void> {
    const main = join(this.c.stateDir, "caddy", "Caddyfile");
    writeFileSync(main, `{\n  email ${this.c.acmeEmail}\n}\nimport /etc/caddy/sites/*.caddy\n`, { mode: 0o644 });
    const have = await this.c.r("docker", ["inspect", "--format", "{{.State.Running}}", "tb-caddy"], {});
    if (have.code === 0 && have.stdout.trim() === "true") return;
    if (have.code === 0) await run(this.c.r, "docker", ["rm", "-f", "tb-caddy"]);
    const dir = join(this.c.stateDir, "caddy");
    await run(this.c.r, "docker", [
      "run",
      "-d",
      "--name",
      "tb-caddy",
      "--restart",
      "unless-stopped",
      "--network",
      "host",
      "-v",
      `${main}:/etc/caddy/Caddyfile:ro`,
      "-v",
      `${dir}:/etc/caddy/sites:ro`,
      "-v",
      "tb-caddy-data:/data",
      this.c.caddyImage,
    ]);
  }

  async stop(ws: string, serviceName: ServiceName): Promise<void> {
    const stopped = this.stoppedSet(ws);
    await run(this.c.r, "docker", ["compose", "-f", this.paths(ws).compose, "stop", serviceName]); // never `down -v`, never `rm -v`
    stopped.add(serviceName);
    mkdirSync(this.paths(ws).dir, { recursive: true, mode: 0o700 });
    writeFileSync(this.paths(ws).stopped, JSON.stringify([...stopped].sort()), { mode: 0o600 });
  }

  async status(ws: string): Promise<ServiceStatus[]> {
    const res = await run(this.c.r, "docker", [
      "ps",
      "-a",
      "--filter",
      `label=com.docker.compose.project=${project(ws)}`,
      "--format",
      '{{.Label "com.docker.compose.service"}}\t{{.Image}}\t{{.State}}\t{{.Status}}',
    ]);
    return res.stdout
      .split("\n")
      .filter(Boolean)
      .map((l) => {
        const [serviceName, image, state, status] = l.split("\t") as [string, string, string, string];
        const restarts = Number(/restarting|Restarting/.test(status) ? 1 : 0);
        return {
          serviceName,
          image,
          state: state === "running" ? (/starting/.test(status) ? "starting" : "running") : state === "exited" || state === "created" ? "stopped" : "failed",
          health: /\(unhealthy\)/.test(status) ? "failing" : /\(healthy\)/.test(status) ? "ok" : "none",
          restarts,
        } satisfies ServiceStatus;
      });
  }

  async volumesOf(ws: string): Promise<string[]> {
    const res = await run(this.c.r, "docker", ["volume", "ls", "--filter", `name=${project(ws)}_`, "--format", "{{.Name}}"]);
    return res.stdout
      .split("\n")
      .map((s) => s.trim())
      .filter(Boolean)
      .sort();
  }
}
